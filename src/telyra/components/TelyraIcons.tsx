export function RenderSemanticIcon(name: string, className?: string) {
  const props = { className: className || '' }
  switch (name) {
    case 'zap': return <ZapIcon {...props} />
    case 'target': return <TargetIcon {...props} />
    case 'cpu': return <CpuIcon {...props} />
    case 'hard-drive': return <HardDriveIcon {...props} />
    case 'grid': return <GridIcon {...props} />
    case 'shield': return <ShieldIcon {...props} />
    case 'tv': return <TvIcon {...props} />
    case 'phone': return <PhoneIcon {...props} />
    case 'download': return <DownloadIcon {...props} />
    default: return <SparklesIcon {...props} />
  }
}
